
import { useEffect, useMemo, useState } from "react";
import { supabase } from "../supabaseClient";

const emptyForm = {
  name: "",
  description: "",
  status: "Active",
};

function RoleMaster() {
  const [roles, setRoles] = useState([]);
  const [search, setSearch] = useState("");

  const [showForm, setShowForm] = useState(false);
  const [editingId, setEditingId] = useState(null);
  const [form, setForm] = useState(emptyForm);

  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");
  const [formError, setFormError] = useState("");

  // FETCH ROLES FROM SUPABASE
  async function fetchRoles() {
    setLoading(true);
    setError("");

    try {
      const { data, error } = await supabase
        .from("role_master")
        .select("id, role_id, role_name, description, status")
        .order("id");

      if (error) throw error;

      const formattedRoles = (data || []).map((role) => ({
        id: role.id,
        roleId: role.role_id,
        name: role.role_name,
        description: role.description || "",
        status: role.status,
      }));

      setRoles(formattedRoles);
    } catch (err) {
      console.error("Role fetch error:", err);
      setError(err.message || "Unable to load roles.");
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    fetchRoles();
  }, []);

  // STATISTICS
  const totalRoles = roles.length;

  const activeRoles = roles.filter(
    (role) => role.status === "Active"
  ).length;

  const inactiveRoles = roles.filter(
    (role) => role.status === "Inactive"
  ).length;

  // SEARCH ROLES
  const filteredRoles = useMemo(() => {
    const query = search.toLowerCase().trim();

    return roles.filter((role) =>
      `${role.roleId} ${role.name} ${role.description} ${role.status}`
        .toLowerCase()
        .includes(query)
    );
  }, [roles, search]);

  // FORM INPUT HANDLER
  function handleChange(e) {
    const { name, value } = e.target;

    setForm((previous) => ({
      ...previous,
      [name]: value,
    }));

    setFormError("");
  }

  // OPEN ADD ROLE FORM
  function handleAddRole() {
    setForm(emptyForm);
    setEditingId(null);
    setFormError("");
    setShowForm(true);
  }

  // CLOSE FORM
  function handleCloseForm() {
    if (saving) return;

    setShowForm(false);
    setEditingId(null);
    setForm(emptyForm);
    setFormError("");
  }

  // SAVE ROLE
  async function handleSubmit(e) {
    e.preventDefault();
    setFormError("");

    const trimmedName = form.name.trim();
    const trimmedDescription = form.description.trim();

    if (!trimmedName || !trimmedDescription) {
      setFormError("Please fill in all required fields.");
      return;
    }

    const duplicate = roles.some(
      (role) =>
        role.id !== editingId &&
        role.name.toLowerCase() === trimmedName.toLowerCase()
    );

    if (duplicate) {
      setFormError("This role already exists.");
      return;
    }

    setSaving(true);

    try {
      let result;

      if (editingId !== null) {
        // UPDATE EXISTING ROLE
        result = await supabase
          .from("role_master")
          .update({
            role_name: trimmedName,
            description: trimmedDescription,
            status: form.status,
          })
          .eq("id", editingId);
      } else {
        // INSERT NEW ROLE
        // role_id is generated by the database.
        result = await supabase
          .from("role_master")
          .insert([
            {
              role_name: trimmedName,
              description: trimmedDescription,
              status: form.status,
            },
          ]);
      }

      if (result.error) throw result.error;

      await fetchRoles();

      setShowForm(false);
      setEditingId(null);
      setForm(emptyForm);
    } catch (err) {
      console.error("Role save error:", err);
      setFormError(err.message || "Unable to save role.");
    } finally {
      setSaving(false);
    }
  }

  // EDIT ROLE
  function handleEdit(role) {
    setForm({
      name: role.name,
      description: role.description,
      status: role.status,
    });

    setEditingId(role.id);
    setFormError("");
    setShowForm(true);
  }

  // ACTIVATE / DEACTIVATE ROLE
  async function toggleStatus(role) {
    const newStatus =
      role.status === "Active" ? "Inactive" : "Active";

    const confirmed = window.confirm(
      `Are you sure you want to ${newStatus === "Active" ? "activate" : "deactivate"} the ${role.name} role?`
    );

    if (!confirmed) return;

    setError("");

    try {
      const { error } = await supabase
        .from("role_master")
        .update({ status: newStatus })
        .eq("id", role.id);

      if (error) throw error;

      await fetchRoles();
    } catch (err) {
      console.error("Role status update error:", err);
      setError(err.message || "Unable to update role status.");
    }
  }

  // DELETE ROLE
  async function handleDelete(role) {
    if (role.name.toLowerCase() === "admin") {
      alert("The Admin role cannot be deleted.");
      return;
    }

    const confirmed = window.confirm(
      `Are you sure you want to delete the ${role.name} role?`
    );

    if (!confirmed) return;

    setError("");

    try {
      // Check whether this role is assigned to any login.
      const { data: assignedLogins, error: checkError } =
        await supabase
          .from("login_master")
          .select("login_id")
          .eq("role_id", role.id)
          .limit(1);

      if (checkError) throw checkError;

      if (assignedLogins && assignedLogins.length > 0) {
        setError(
          "This role is assigned to an employee login and cannot be deleted. Deactivate it instead."
        );
        return;
      }

      const { error } = await supabase
        .from("role_master")
        .delete()
        .eq("id", role.id);

      if (error) throw error;

      await fetchRoles();
    } catch (err) {
      console.error("Role delete error:", err);

      setError(
        err.message ||
          "Unable to delete role. It may be referenced by another record."
      );
    }
  }

  return (
    <div className="page-content role-master-page">

      {/* PAGE HEADER */}
      <div className="master-header">
        <div>
          <div className="master-breadcrumb">
            Admin <span>/</span> Master Data
          </div>

          <h1>Role Master</h1>

          <p>
            Create and manage system roles and their descriptions.
          </p>
        </div>

        <button
          type="button"
          className="master-primary-btn"
          onClick={handleAddRole}
        >
          + Add New Role
        </button>
      </div>

      {/* STATISTICS CARDS */}
      <div className="master-stats">

        <div className="master-stat-card">
          <div className="master-stat-icon">
            <span>♙</span>
          </div>

          <div>
            <p>Total Roles</p>
            <h2>{totalRoles}</h2>
          </div>
        </div>

        <div className="master-stat-card">
          <div className="master-stat-icon">
            <span>✓</span>
          </div>

          <div>
            <p>Active Roles</p>
            <h2>{activeRoles}</h2>
          </div>
        </div>

        <div className="master-stat-card">
          <div className="master-stat-icon">
            <span>−</span>
          </div>

          <div>
            <p>Inactive Roles</p>
            <h2>{inactiveRoles}</h2>
          </div>
        </div>

      </div>

      {/* ERROR MESSAGE */}
      {error && (
        <p className="employee-form-error">{error}</p>
      )}

      {/* ADD / EDIT ROLE FORM */}
      {showForm && (
        <div className="master-form-card">

          <div className="master-form-heading">
            <div>
              <h2>
                {editingId !== null
                  ? "Edit Role"
                  : "Add New Role"}
              </h2>

              <p>
                Enter the role information below.
              </p>
            </div>

            <button
              type="button"
              className="master-close-btn"
              onClick={handleCloseForm}
              aria-label="Close form"
            >
              ✕
            </button>
          </div>

          <form onSubmit={handleSubmit}>

            <div className="master-form-grid">

              <div className="master-field">
                <label htmlFor="roleName">
                  Role Name *
                </label>

                <input
                  id="roleName"
                  type="text"
                  name="name"
                  placeholder="Enter role name"
                  value={form.name}
                  onChange={handleChange}
                  required
                />
              </div>

              <div className="master-field">
                <label htmlFor="roleStatus">
                  Status
                </label>

                <select
                  id="roleStatus"
                  name="status"
                  value={form.status}
                  onChange={handleChange}
                >
                  <option value="Active">Active</option>
                  <option value="Inactive">Inactive</option>
                </select>
              </div>

              <div className="master-field role-description-field">
                <label htmlFor="roleDescription">
                  Description *
                </label>

                <textarea
                  id="roleDescription"
                  name="description"
                  placeholder="Enter role description"
                  value={form.description}
                  onChange={handleChange}
                  rows="3"
                  required
                />
              </div>

            </div>

            {formError && (
              <p className="employee-form-error">{formError}</p>
            )}

            <div className="master-actions">

              <button
                type="button"
                className="master-cancel-btn"
                onClick={handleCloseForm}
                disabled={saving}
              >
                Cancel
              </button>

              <button
                type="submit"
                className="master-primary-btn"
                disabled={saving}
              >
                {saving
                  ? "Saving..."
                  : editingId !== null
                    ? "Update Role"
                    : "Save Role"}
              </button>

            </div>

          </form>
        </div>
      )}

      {/* ROLE LIST */}
      <div className="master-table-card">

        <div className="master-table-header">

          <div>
            <h2>Role List</h2>

            <p>
              Manage all roles available in LeaveFlow.
            </p>
          </div>

          <input
            type="text"
            className="master-search"
            placeholder="Search roles..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
          />

        </div>

        {/* TABLE */}
        <div className="master-table-wrapper">

          <table className="master-table">

            <thead>
              <tr>
                <th>Role ID</th>
                <th>Role Name</th>
                <th>Description</th>
                <th>Status</th>
                <th>Actions</th>
              </tr>
            </thead>

            <tbody>

              {loading ? (
                <tr>
                  <td colSpan="5" className="master-empty">
                    Loading roles...
                  </td>
                </tr>
              ) : filteredRoles.length > 0 ? (

                filteredRoles.map((role) => (

                  <tr key={role.id}>

                    <td>{role.roleId}</td>

                    <td>
                      <strong>{role.name}</strong>
                    </td>

                    <td>{role.description}</td>

                    <td>
                      <span
                        className={`role-status-badge ${
                          role.status === "Active"
                            ? "active"
                            : "inactive"
                        }`}
                      >
                        <span className="status-dot"></span>
                        {role.status}
                      </span>
                    </td>

                    <td>
                      <div className="role-row-actions">

                        <button
                          type="button"
                          className="role-edit-btn"
                          onClick={() => handleEdit(role)}
                        >
                          Edit
                        </button>

                        <button
                          type="button"
                          className="role-toggle-btn"
                          onClick={() => toggleStatus(role)}
                        >
                          {role.status === "Active"
                            ? "Deactivate"
                            : "Activate"}
                        </button>

                        <button
                          type="button"
                          className="role-delete-btn"
                          onClick={() => handleDelete(role)}
                        >
                          Delete
                        </button>

                      </div>
                    </td>

                  </tr>

                ))

              ) : (

                <tr>
                  <td colSpan="5" className="master-empty">
                    No roles found.
                  </td>
                </tr>

              )}

            </tbody>

          </table>

        </div>

        {/* TABLE FOOTER */}
        <div className="role-table-footer">
          Showing {filteredRoles.length} of {totalRoles} roles
        </div>

      </div>

    </div>
  );
}

export default RoleMaster;
